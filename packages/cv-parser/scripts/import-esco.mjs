// Generates src/skills-esco.ts from the public ESCO API (ICT field, ISCED-F 061, and the skills below it).
// Usage: node scripts/import-esco.mjs   (needs network; re-run when ESCO publishes a new version)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const API = 'https://ec.europa.eu/esco/api/resource';
const ROOT = 'http://data.europa.eu/esco/isced-f/061';
const MAX_DEPTH = 3;
const CONCURRENCY = 6;
const OUT = fileURLToPath(new URL('../src/skills-esco.ts', import.meta.url));

async function get(kind, uri, attempt = 1) {
  const res = await fetch(`${API}/${kind}?uri=${encodeURIComponent(uri)}&language=en`);
  if (res.ok) return res.json();
  if (attempt < 4 && (res.status === 429 || res.status >= 500)) {
    await new Promise((r) => setTimeout(r, 1000 * attempt));
    return get(kind, uri, attempt + 1);
  }
  throw new Error(`${res.status} for ${uri}`);
}

const links = (node, key) => [node._links?.[key] ?? []].flat();

// Breadth-first over the ICT concepts, then their skills (and narrower skills) up to MAX_DEPTH.
const skills = new Map();
let queue = [{ kind: 'concept', uri: ROOT, depth: 0 }];
const seen = new Set([ROOT]);
while (queue.length > 0) {
  const batch = queue.splice(0, CONCURRENCY);
  const nodes = await Promise.all(batch.map((item) => get(item.kind, item.uri).then((node) => ({ item, node }))));
  for (const { item, node } of nodes) {
    if (item.kind === 'skill') skills.set(item.uri, node);
    const next = [
      ...links(node, 'narrowerConcept').map((l) => ({ kind: 'concept', uri: l.uri, depth: item.depth })),
      ...links(node, 'narrowerSkill').map((l) => ({ kind: 'skill', uri: l.uri, depth: item.kind === 'skill' ? item.depth + 1 : 0 })),
    ];
    for (const n of next) {
      if (seen.has(n.uri) || n.depth > MAX_DEPTH) continue;
      seen.add(n.uri);
      queue.push(n);
    }
  }
  process.stdout.write(`\rfetched ${skills.size} skills, ${queue.length} queued   `);
}
process.stdout.write('\n');

const GENERIC = /^(?:types? of|principles? of|methods? of|process(?:es)? of|characteristics of|features of|functionalities of|use of|theory of)\b/i;
// ESCO alternative labels that name a different tool or are not skills on a CV.
const ALIAS_DENY = new Set(['mocha', 'subquery', 'java posse', 'escript', 'dot net', 'live script', 'access', 'javax']);
const clean = (label) => label.replace(/\s*\([^)]*\)\s*/g, ' ').replace(/\s+/g, ' ').trim();
const usable = (label) =>
  label.length >= 2 && label.length <= 40 && label.split(' ').length <= 4 && /\p{L}/u.test(label) && !GENERIC.test(label) && !label.includes('|');

const entries = [];
for (const node of skills.values()) {
  // Knowledge items are nouns ("Python", "SAP R3"); "skill" items are verb phrases ("use spreadsheets software").
  const type = links(node, 'hasSkillType')[0]?.title ?? '';
  if (!/knowledge/i.test(type)) continue;
  const canonical = clean(node.preferredLabel?.en ?? node.title ?? '');
  if (!usable(canonical)) continue;
  const aliases = new Set();
  for (const label of [node.preferredLabel?.fr, ...(node.alternativeLabel?.en ?? []), ...(node.alternativeLabel?.fr ?? [])]) {
    if (typeof label !== 'string') continue;
    const alias = clean(label);
    if (usable(alias) && alias.toLowerCase() !== canonical.toLowerCase() && !ALIAS_DENY.has(alias.toLowerCase())) aliases.add(alias);
  }
  entries.push([canonical, ...[...aliases].slice(0, 8)].join('|'));
}
entries.sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));

const header = `/**
 * Generated by scripts/import-esco.mjs from ESCO (European Skills, Competences, Qualifications and Occupations),
 * ICT field (ISCED-F 061): knowledge items with English and French labels, ${entries.length} entries.
 * Source: https://esco.ec.europa.eu — © European Union, reused under Commission Decision 2011/833/EU.
 * Do not edit by hand; matched only inside skills sections (see skills.ts).
 */
`;
writeFileSync(OUT, `${header}export const ESCO_SKILL_ENTRIES: string[] = [\n${entries.map((e) => `  ${JSON.stringify(e)},`).join('\n')}\n];\n`);
console.log(`wrote ${entries.length} entries to ${OUT}`);
